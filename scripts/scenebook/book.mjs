// Export to and import from the Scene Book Markdown. The CLIs (export-scenes.mjs,
// import-scenes.mjs) and the round-trip test all call these.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';
import { COMBINED, ROOT, SCENES_DIR, loadAll, version } from './content.mjs';
import { STATUSES, applyValues, mdName, parse, planItem, render } from './format.mjs';
import { writeJson } from './jsonedit.mjs';

const MANIFEST = '.export-manifest.json';
const sha = (s) => createHash('sha1').update(s).digest('hex');

function readManifest(dir) {
  try {
    return JSON.parse(readFileSync(join(dir, MANIFEST), 'utf8'));
  } catch {
    return {};
  }
}

const READING_GUIDE = [
  '## How to read a scene',
  '- Narration is second person, present tense. Each paragraph is one block of text.',
  '- **Bold** lines are the player\'s choices. The arrow (→) shows what happens.',
  '- *Record* lines are what the game writes to the player\'s record. The record states facts. It never scores or judges.',
  '- [Brackets] are names Jim still needs to fill. {Braces} are filled in by the game: the player\'s name, the clock, their standard.',
  '- Small headings are the steps of a scene, by the name the game uses. Italic lines that say when something shows, or where a choice goes next, come from the game\'s structure.',
  '- The status and Jim\'s notes (Claude\'s guesses and JIM questions) sit at the top of each scene.',
].join('\n').replace('## How to read a scene\n', '## How to read a scene\n\n');

function combinedBook(all, rendered) {
  const parts = [
    '# Framework Game: Scene Book drafts',
    'Every scene and encounter in the solo slice, in review order. Generated by `npm run export-scenes` from the content files. Edit the single-scene files in docs/scenes/ and run `npm run import-scenes` to bring the words back into the game. This combined file is for reading and for Google Drive; it is not imported.',
    READING_GUIDE,
    '## Contents',
  ];
  for (const g of all.groups) {
    parts.push(`**${g.title}**`);
    parts.push(g.items.map((it) => `- ${it.json.title} (${it.json.status})`).join('\n'));
  }
  for (const g of all.groups) {
    parts.push(`## ${g.title}`);
    for (const it of g.items) parts.push(rendered.get(it).trimEnd());
  }
  return `${parts.join('\n\n')}\n`;
}

/**
 * Write every scene and encounter to Markdown.
 * A file that was edited since the last export (and not imported yet) is left alone
 * unless force is on, so an export can't wipe out Jim's edits.
 */
export function exportBook({ dir = SCENES_DIR, combined = COMBINED, force = false, forceNames = new Set(), quiet = false } = {}) {
  const all = loadAll();
  mkdirSync(dir, { recursive: true });
  const manifest = readManifest(dir);
  const rendered = new Map();
  const report = { written: [], unchanged: [], kept: [], removed: [] };
  const names = new Set();
  for (const it of all.items) {
    const plan = planItem(it, all);
    const md = render(plan);
    rendered.set(it, render(plan, { shift: 2 }));
    const name = mdName(it);
    names.add(name);
    const path = join(dir, name);
    if (existsSync(path)) {
      const cur = readFileSync(path, 'utf8');
      if (cur === md) {
        manifest[name] = sha(md);
        report.unchanged.push(name);
        continue;
      }
      const edited = manifest[name] ? sha(cur) !== manifest[name] : true;
      if (edited && !force && !forceNames.has(name)) {
        report.kept.push(name);
        continue;
      }
    }
    writeFileSync(path, md);
    manifest[name] = sha(md);
    report.written.push(name);
  }
  for (const f of readdirSync(dir).filter((x) => x.endsWith('.md'))) {
    if (names.has(f)) continue;
    const cur = readFileSync(join(dir, f), 'utf8');
    if (force || (manifest[f] && sha(cur) === manifest[f])) {
      rmSync(join(dir, f));
      delete manifest[f];
      report.removed.push(f);
    } else report.kept.push(f);
  }
  writeFileSync(join(dir, MANIFEST), `${JSON.stringify(manifest, null, 2)}\n`);
  if (combined) writeFileSync(combined, combinedBook(all, rendered));
  if (!quiet) {
    console.log(`Scene Book export: ${all.items.length} scenes and encounters.`);
    console.log(`  ${report.written.length} written, ${report.unchanged.length} unchanged${report.removed.length ? `, ${report.removed.length} removed (no content file any more)` : ''}.`);
    if (report.kept.length) {
      console.log(`  Left alone because they have edits that aren't imported yet (run npm run import-scenes, or export with --force to overwrite):`);
      for (const k of report.kept) console.log(`    ${k}`);
    }
    console.log(`  Files: ${relative(ROOT, dir)}/  and  ${combined ? relative(ROOT, combined) : '(no combined file)'}`);
  }
  return report;
}

/** Line diff for the report: what was removed and what was added, in order. */
function lineDiff(a, b) {
  const n = a.length;
  const m = b.length;
  const L = Array.from({ length: n + 1 }, () => new Array(m + 1).fill(0));
  for (let i = n - 1; i >= 0; i--) for (let j = m - 1; j >= 0; j--) L[i][j] = a[i] === b[j] ? L[i + 1][j + 1] + 1 : Math.max(L[i + 1][j], L[i][j + 1]);
  const out = [];
  let i = 0;
  let j = 0;
  while (i < n || j < m) {
    if (i < n && j < m && a[i] === b[j]) {
      i++;
      j++;
    } else if (i < n && (j === m || L[i + 1][j] >= L[i][j + 1])) out.push(`- ${a[i++]}`);
    else out.push(`+ ${b[j++]}`);
  }
  return out;
}

/**
 * Read edited Markdown back. Returns per-item results; writes nothing unless apply is true,
 * and writes nothing at all if any file was refused.
 */
export function importBook({ dir = SCENES_DIR, apply = false, quiet = false, reexport = true } = {}) {
  const all = loadAll();
  const byName = new Map(all.items.map((it) => [mdName(it), it]));
  const results = [];
  const files = existsSync(dir) ? readdirSync(dir).filter((x) => x.endsWith('.md')).sort() : [];
  const order = (name) => {
    const it = byName.get(name);
    return it ? all.items.indexOf(it) : 1e9;
  };
  files.sort((a, b) => order(a) - order(b));
  for (const name of files) {
    const it = byName.get(name);
    const md = readFileSync(join(dir, name), 'utf8');
    if (!it) {
      results.push({ name, errors: ['No scene or encounter has this id. Scene files are named <id>.md, encounters encounter-<id>.md.'] });
      continue;
    }
    const r = { name, it, errors: [], changes: [] };
    results.push(r);
    const v = /Version: `([0-9a-f]+)`/.exec(md);
    if (v && v[1] !== version(it.json)) {
      r.errors.push(`${it.file} changed after this Markdown was exported, so these edits may undo newer work. Nothing was read from it. Export again, then redo the edits (or ask Claude to merge them).`);
      continue;
    }
    const plan = planItem(it, all);
    const parsed = parse(md, plan);
    if (parsed.errors.length) {
      r.errors.push(...parsed.errors);
      continue;
    }
    const res = applyValues(it.json, plan, parsed.values);
    r.changes = res.changes;
    r.newJson = res.json;
    r.paths = res.paths;
    if (!res.changes.length) continue;
    if (it.json.status === 'locked') {
      r.errors.push(`"${it.json.title}" is locked. Locked scenes are approved Scene Book text, so import won't change them. Undo the edits in ${name}, or set the scene back to draft in the JSON first if you mean to reopen it.`);
      continue;
    }
    if (!STATUSES.includes(res.json.status)) {
      r.errors.push(`Status must be one of: ${STATUSES.map((s) => `"${s}"`).join(', ')}. Found "${res.json.status}".`);
    }
  }

  const changed = results.filter((r) => r.changes && r.changes.length && !r.errors.length);
  const refused = results.filter((r) => r.errors.length);
  const missing = all.items.filter((it) => !files.includes(mdName(it)));
  if (!quiet) {
    for (const r of results) {
      if (!r.changes?.length && !r.errors.length) continue;
      const title = r.it ? `${r.it.json.title}  (${r.it.file})` : r.name;
      console.log(`\n${r.errors.length ? 'REFUSED' : 'Changed'}: ${title}`);
      for (const c of r.changes ?? []) {
        console.log(`  ${c.label}`);
        for (const l of lineDiff(c.old, c.new)) console.log(`    ${l}`);
      }
      for (const e of r.errors) console.log(`  ! ${e}`);
    }
    const lines = changed.reduce((n, r) => n + r.changes.reduce((x, c) => x + lineDiff(c.old, c.new).length, 0), 0);
    console.log(`\nScene Book import: ${files.length} files read. ${changed.length} with changes (${lines} changed lines). ${refused.length} refused.`);
    if (missing.length) console.log(`  No Markdown for: ${missing.map(mdName).join(', ')}. Run npm run export-scenes.`);
  }
  if (refused.length) {
    if (!quiet) console.log(apply ? 'Nothing written, because some files were refused. Fix those and run it again.' : 'Fix the refused files before applying.');
    return { results, changed, refused, wrote: [] };
  }
  const wrote = [];
  if (apply && changed.length) {
    for (const r of changed) {
      const { text, fallback } = writeJson(r.it.text, r.it.json, r.newJson, r.paths);
      writeFileSync(r.it.abs, text);
      wrote.push({ file: r.it.file, fallback });
    }
    if (!quiet) {
      console.log(`Wrote ${wrote.length} content files:`);
      for (const w of wrote) console.log(`  ${w.file}${w.fallback ? '  (rewritten in the standard layout)' : ''}`);
    }
    if (reexport) exportBook({ dir, force: false, forceNames: new Set(changed.map((r) => r.name)), quiet: true });
    if (!quiet) console.log('Re-exported their Markdown with the new version. Next: npm run check-content, then npm run build.');
  } else if (!quiet && changed.length) console.log('Nothing written. Run with --apply to write these changes.');
  return { results, changed, refused, wrote };
}
